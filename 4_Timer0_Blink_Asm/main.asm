.device ATmega32
.include "m32def.inc"

; ----- Только один вектор сброса -----
.org 0x0000
    rjmp RESET

RESET:
    ; 1. Инициализация стека
    ldi r16, high(RAMEND)
    out SPH, r16 
    ldi r16, low(RAMEND)
    out SPL, r16

    ; 2. Настройка порта B0 на выход
    ser r16
    out DDRB, r16
    clr r16
    out PORTB, r16

    ; 3. Настройка Таймера 0 в режим CTC (сброс при совпадении)
    ; Задаем порог счета в OCR0 (число 156)
    ldi r16, 156
    out OCR0, r16

    ; Запускаем таймер: режим CTC (WGM01) + предделитель /1024 (CS02 и CS00)
    ; ВНИМАНИЕ: Прерывания (TIMSK и sei) мы здесь НЕ включаем!
    ldi r16, (1<<WGM01) | (1<<CS02) | (1<<CS00)
    out TCCR0, r16

; ----- Основной цикл программы -----
MAIN_LOOP:
    ; Проверяем флаг совпадения таймера (OCF0) в регистре TIFR
    in r16, TIFR
    andi r16, (1<<OCF0)     ; Проверяем, поднялся ли 1-й бит (совпадение произошло?)
    breq MAIN_LOOP          ; Если бит равен 0, таймер еще не досчитал, возвращаемся в начало цикла

    ; --- Если таймер досчитал и сбросился в 0 ---
    ; 1. Переключаем светодиод на PB0
    in r16, PORTB
    ldi r18, (1<<PB0)
    eor r16, r18
    out PORTB, r16

    ; 2. Очищаем флаг совпадения TIFR
    ; В AVR флаги таймеров очищаются записью ЕДИНИЦЫ в этот бит!
    ldi r16, (1<<OCF0)
    out TIFR, r16

    rjmp MAIN_LOOP          ; Уходим на новый круг ожидания
